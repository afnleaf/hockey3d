// Generates public/icon_glyphs.js from icons/<typeDescKey>.svg.
// Each file is a standalone SVG so it opens in any editor; only the inner
// markup is kept, and the root must match the attributes iconSvg emits.
import { readdir } from "node:fs/promises";
import { join } from "node:path";

const VIEWBOX = "0 0 96 96";
const dir = join(import.meta.dir, "icons");
const glyphs: Record<string, string> = {};

// Files starting with "_" are shared parts, referenced from icons as
// <use href="_part.svg#id" transform="..."/> and inlined here, because
// external <use> references do not resolve inside the page.
const files = (await readdir(dir)).filter(f => f.endsWith(".svg")).sort();
const parts: Record<string, string> = {};

function inner(name: string, text: string): string {
    const root = text.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>/);
    if (!root) throw new Error(`${name}: no <svg> root`);
    const viewBox = root[1].match(/viewBox="([^"]*)"/)?.[1];
    if (viewBox !== VIEWBOX) {
        throw new Error(`${name}: viewBox "${viewBox}", expected "${VIEWBOX}"`);
    }
    return root[2]
        .replace(/<!--[\s\S]*?-->/g, "")
        .replace(/<(sodipodi:namedview|metadata)\b[\s\S]*?(\/>|<\/\1>)/g, "")
        .replace(/<defs\b[^>]*(\/>|>\s*<\/defs>)/g, "")
        .replace(/\s(sodipodi|inkscape|xml):[\w-]+="[^"]*"/g, "")
        .replace(/\s*\n\s*/g, "")
        .trim();
}

for (const name of files.filter(f => f.startsWith("_"))) {
    const body = inner(name, await Bun.file(join(dir, name)).text());
    for (const m of body.matchAll(/<g id="([^"]+)">([\s\S]*?)<\/g>/g)) {
        parts[`${name}#${m[1]}`] = m[2];
    }
}

for (const name of files.filter(f => !f.startsWith("_"))) {
    const body = inner(name, await Bun.file(join(dir, name)).text());
    glyphs[name.slice(0, -4)] = body.replace(
        /<use href="([^"]+)" transform="([^"]*)"\/>/g,
        (_, ref, t) => {
            const part = parts[ref];
            if (!part) throw new Error(`${name}: unknown part ${ref}`);
            return `<g transform="${t} translate(-48 -48)" fill="currentColor" stroke="none">${part}</g>`;
        },
    );
}
if (!glyphs.fallback) throw new Error("icons/fallback.svg missing");

await Bun.write(
    join(import.meta.dir, "public/icon_glyphs.js"),
    "// Generated by build_icons.ts from icons/*.svg. Do not edit.\n"
        + `export const VIEWBOX = ${JSON.stringify(VIEWBOX)};\n`
        + `export const GLYPHS = ${JSON.stringify(glyphs, null, 4)};\n`,
);
console.log(`icon_glyphs.js: ${Object.keys(glyphs).length} glyphs`);
